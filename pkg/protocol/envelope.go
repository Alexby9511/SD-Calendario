// Package protocol implements the signed message envelope shared by the
// cluster nodes and the desktop client.
//
// The signing input is derived exclusively from the envelope fields listed in
// docs/arquitectura.md §6.1. Anything the leader assigns (proposed_at,
// log_index) stays outside the signature, so a client can produce the exact
// same bytes on both sides.
package protocol

import (
	"crypto/ed25519"
	"encoding/json"
	"errors"
	"fmt"
	"strings"
)

// Type is a command kind from docs/arquitectura.md §6.2.
type Type string

const (
	TypeRequest      Type = "REQUEST"
	TypeReply        Type = "REPLY"
	TypeCounter      Type = "COUNTER"
	TypeDeclineCount Type = "DECLINECOUNTER"
	TypeCancel       Type = "CANCEL"
	TypeClosePoll    Type = "CLOSE_POLL"
	TypeReopen       Type = "REOPEN"
	TypeReanchor     Type = "REANCHOR"
	TypeBusyUpdate   Type = "BUSY_UPDATE"
	TypeEvaluate     Type = "EVALUATE"
)

// Valid reports whether t is a known command type.
func (t Type) Valid() bool {
	switch t {
	case TypeRequest, TypeReply, TypeCounter, TypeDeclineCount, TypeCancel,
		TypeClosePoll, TypeReopen, TypeReanchor, TypeBusyUpdate, TypeEvaluate:
		return true
	}
	return false
}

// IsSystem reports whether t is generated by the leader and therefore unsigned.
func (t Type) IsSystem() bool { return t == TypeEvaluate }

// Envelope is the wire representation of a command.
//
// ClientSentAt is a string on purpose: time.Time marshals with variable
// precision, which would make otherwise identical messages produce different
// signing bytes.
type Envelope struct {
	DeploymentID string          `json:"deployment_id"`
	GroupID      string          `json:"group_id"`
	MsgID        string          `json:"msg_id"`
	Type         Type            `json:"type"`
	UID          string          `json:"uid"`
	SenderID     string          `json:"sender_id"`
	KeyID        string          `json:"key_id"`
	Sequence     uint64          `json:"sequence"`
	SeenSequence uint64          `json:"seen_sequence"`
	ClientSentAt string          `json:"client_sent_at"`
	Payload      json.RawMessage `json:"payload"`
	Signature    []byte          `json:"signature,omitempty"`
}

// ErrUnsignedType is returned when a caller tries to sign a system command.
var ErrUnsignedType = errors.New("protocol: system commands are not signed by clients")

// signingFields mirrors the "bytes firmados" list of §6.1. It is a separate
// type on purpose: adding a field to Envelope must not silently change what is
// signed.
type signingFields struct {
	DeploymentID string          `json:"deployment_id"`
	GroupID      string          `json:"group_id"`
	MsgID        string          `json:"msg_id"`
	Type         Type            `json:"type"`
	UID          string          `json:"uid"`
	SenderID     string          `json:"sender_id"`
	KeyID        string          `json:"key_id"`
	Sequence     uint64          `json:"sequence"`
	SeenSequence uint64          `json:"seen_sequence"`
	ClientSentAt string          `json:"client_sent_at"`
	Payload      json.RawMessage `json:"payload"`
}

// SigningInput returns the canonical bytes covered by the signature.
func (e *Envelope) SigningInput() ([]byte, error) {
	payload, err := Canonicalize(e.Payload)
	if err != nil {
		return nil, fmt.Errorf("payload: %w", err)
	}
	fields := signingFields{
		DeploymentID: e.DeploymentID,
		GroupID:      e.GroupID,
		MsgID:        e.MsgID,
		Type:         e.Type,
		UID:          e.UID,
		SenderID:     e.SenderID,
		KeyID:        e.KeyID,
		Sequence:     e.Sequence,
		SeenSequence: e.SeenSequence,
		ClientSentAt: e.ClientSentAt,
		Payload:      payload,
	}
	raw, err := json.Marshal(fields)
	if err != nil {
		return nil, fmt.Errorf("envelope: %w", err)
	}
	return Canonicalize(raw)
}

// Sign fills Signature with an Ed25519 signature over SigningInput.
func (e *Envelope) Sign(priv ed25519.PrivateKey) error {
	if e.Type.IsSystem() {
		return ErrUnsignedType
	}
	if len(priv) != ed25519.PrivateKeySize {
		return fmt.Errorf("protocol: bad private key size %d", len(priv))
	}
	input, err := e.SigningInput()
	if err != nil {
		return err
	}
	e.Signature = ed25519.Sign(priv, input)
	return nil
}

// Verify checks the signature with the public key that KeyID resolves to.
// It does not check authorization, only authenticity.
func (e *Envelope) Verify(pub ed25519.PublicKey) error {
	if len(pub) != ed25519.PublicKeySize {
		return fmt.Errorf("protocol: bad public key size %d", len(pub))
	}
	if len(e.Signature) != ed25519.SignatureSize {
		return fmt.Errorf("protocol: bad signature size %d", len(e.Signature))
	}
	input, err := e.SigningInput()
	if err != nil {
		return err
	}
	if !ed25519.Verify(pub, input, e.Signature) {
		return errors.New("protocol: invalid signature")
	}
	return nil
}

// Validate checks structural invariants that do not depend on replicated
// state. State-dependent rules (sequence, state machine, roster) belong to the
// FSM.
func (e *Envelope) Validate() error {
	for _, f := range []struct {
		name  string
		value string
	}{
		{"deployment_id", e.DeploymentID},
		{"group_id", e.GroupID},
		{"msg_id", e.MsgID},
		{"uid", e.UID},
		{"sender_id", e.SenderID},
	} {
		if strings.TrimSpace(f.value) == "" {
			return fmt.Errorf("protocol: empty %s", f.name)
		}
	}
	if !e.Type.Valid() {
		return fmt.Errorf("protocol: unknown type %q", e.Type)
	}
	if !e.Type.IsSystem() && strings.TrimSpace(e.KeyID) == "" {
		return fmt.Errorf("protocol: empty key_id")
	}
	if len(e.Payload) == 0 {
		return fmt.Errorf("protocol: empty payload")
	}
	if _, err := Canonicalize(e.Payload); err != nil {
		return fmt.Errorf("protocol: payload: %w", err)
	}
	// Creation is the only command allowed to introduce a uid, and it must
	// live in the sender's namespace (§4.3).
	if e.Type == TypeRequest && e.Sequence == 1 {
		if !strings.HasPrefix(e.UID, e.SenderID+":") {
			return fmt.Errorf("protocol: uid %q outside sender namespace %q", e.UID, e.SenderID)
		}
	}
	return nil
}

// MessageHash returns the digest used for deduplication. The signature is
// excluded: Ed25519 is deterministic per RFC 8032, but not every library
// produces the same valid signature for the same bytes.
func (e *Envelope) MessageHash() ([32]byte, error) {
	input, err := e.SigningInput()
	if err != nil {
		return [32]byte{}, err
	}
	return sha256Sum(input), nil
}
